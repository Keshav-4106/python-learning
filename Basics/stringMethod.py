name = "keshav somani"

print(name.capitalize())              # first letter capital karta hai

print(name.count("a"))                 # "a" kitni baar aaya hai count karta hai

print(name.lower())                    # pure text ko lowercase me convert karta hai

print(name.endswith("i"))              # check karta hai text "i" se end ho raha hai ya nahi

print(name.find("s"))                  # "s" ka index/position batata hai

print(name.title())                    # har word ka first letter capital karta hai

print(name.strip())                    # start/end ke extra spaces remove karta hai

print(name.replace("somani", "maheshwari"))  # old word ko new word se replace karta hai

print(name.startswith("k"))            # check karta hai text "k" se start ho raha hai ya nahi

print(name.upper())                    # pure text ko uppercase me convert karta hai



