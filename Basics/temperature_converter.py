#Take input in celsius and print its equivalent in Farenheit and Kelvin.
#(Use explicit type conversion and arithmetic operator)


#code start
celsius=int(input("enter the value of celsius:"))
Farenheit= (celsius*9/5) + 32
Kelvin= celsius + 273.15
print("Farenheit=",Farenheit)
print("Kelvin=",Kelvin)


